# -*- coding: utf-8 -*-
"""Streamlit dashboard for the Ethiopia Agricultural Drought Risk project."""
from pathlib import Path
import joblib
import pandas as pd
import streamlit as st

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "best_drought_model.joblib"

st.set_page_config(page_title="Ethiopia Agricultural Drought Risk", page_icon="🌾",
                   layout="wide")

st.title("🌾 Agricultural Drought Risk Prediction")
st.caption("Machine-learning-based drought risk assessment and agricultural recommendations for Ethiopia")

@st.cache_resource
def load_bundle(path):
    return joblib.load(path)

if not MODEL_PATH.exists():
    st.error("Trained model file not found: best_drought_model.joblib")
    st.markdown(
        "Upload the model generated by running `drought.py` (or your original Colab-trained "
        "model bundle) into the same GitHub folder as `app.py`."
    )
    st.code(
        "app.py\n"
        "drought.py\n"
        "best_drought_model.joblib  # required\n"
        "requirements.txt\n"
        "README.md\n"
        ".gitignore"
    )
    st.stop()

try:
    bundle = load_bundle(MODEL_PATH)
    model = bundle["model"]
    label_encoder = bundle["label_encoder"]
    feature_columns = bundle["feature_columns"]
except Exception as exc:
    st.error(f"Could not load the model bundle: {exc}")
    st.info("The file must be the joblib bundle containing model, label_encoder and feature_columns.")
    st.stop()

# Read feature types and learned categories from the fitted preprocessing pipeline.
prep = model.named_steps["prep"]
numeric_cols, categorical_cols = [], []
for transformer_name, transformer, cols in prep.transformers_:
    if transformer_name == "num":
        numeric_cols = list(cols)
    elif transformer_name == "cat":
        categorical_cols = list(cols)

cat_options = {}
try:
    cat_pipe = prep.named_transformers_["cat"]
    encoder = cat_pipe.named_steps["oh"]
    cat_options = {col: list(values) for col, values in zip(categorical_cols, encoder.categories_)}
except Exception:
    pass

num_defaults = {}
try:
    num_pipe = prep.named_transformers_["num"]
    imputer = num_pipe.named_steps["imp"]
    num_defaults = {col: float(value) for col, value in zip(numeric_cols, imputer.statistics_)}
except Exception:
    pass

def numeric_bounds(col, default):
    key = col.lower()
    if "rainfall" in key or "evapotranspiration" in key:
        return 0.0, 3000.0
    if "temp" in key:
        return -10.0, 60.0
    if "humidity" in key or "moisture" in key:
        return 0.0, 100.0
    return min(0.0, default), max(100.0, default + 100.0)

st.sidebar.header("📍 Location and Climate Inputs")
st.sidebar.caption("Enter values for the location and observation you want to assess.")
input_values = {}

with st.sidebar.form("prediction_form"):
    for col in feature_columns:
        if col in categorical_cols:
            opts = cat_options.get(col, [])
            if opts:
                input_values[col] = st.selectbox(col.replace("_", " "), opts)
            else:
                input_values[col] = st.text_input(col.replace("_", " "))
        elif col in numeric_cols:
            default = num_defaults.get(col, 0.0)
            low, high = numeric_bounds(col, default)
            default = min(max(default, low), high)
            input_values[col] = st.number_input(
                col.replace("_", " "), min_value=float(low), max_value=float(high),
                value=float(default), step=0.1, format="%.2f"
            )
        else:
            input_values[col] = st.text_input(col.replace("_", " "))
    submitted = st.form_submit_button("🔍 Predict Drought Risk", use_container_width=True)

# Dashboard overview cards
st.subheader("📊 Assessment Dashboard")
c1, c2, c3 = st.columns(3)
c1.metric("Model", type(model.named_steps["model"]).__name__)
c2.metric("Input features", len(feature_columns))
c3.metric("Risk classes", len(label_encoder.classes_))

if submitted:
    sample = pd.DataFrame([{col: input_values[col] for col in feature_columns}],
                          columns=feature_columns)
    try:
        pred_encoded = model.predict(sample)[0]
        predicted_label = label_encoder.inverse_transform([int(pred_encoded)])[0]
        probabilities = model.predict_proba(sample)[0]
        classes = label_encoder.inverse_transform(model.named_steps["model"].classes_.astype(int))
        prob_df = pd.DataFrame({"Drought Risk Category": classes,
                                "Probability": probabilities})
        prob_df = prob_df.sort_values("Probability", ascending=False)

        st.divider()
        st.subheader("🚨 Drought Risk Prediction")
        risk_colors = {
            "No Drought": "🟢",
            "Moderate Drought": "🟠",
            "Severe Drought": "🔴"
        }
        st.markdown(f"## {risk_colors.get(predicted_label, '🌾')} {predicted_label}")
        st.caption("The probability shown is the model's estimated class probability, not a guarantee.")

        left, right = st.columns([1, 1])
        with left:
            st.markdown("**Class probability**")
            st.bar_chart(prob_df.set_index("Drought Risk Category"))
        with right:
            st.markdown("**Assessment inputs**")
            st.dataframe(sample.T.rename(columns={0: "Input value"}),
                         use_container_width=True)

        advice = {
            "No Drought": "Continue normal crop management. Monitor rainfall and soil moisture, and conserve water for possible dry periods.",
            "Moderate Drought": "Consider early-maturing and drought-tolerant crops. Use mulching, conserve rainwater, and monitor fields regularly.",
            "Severe Drought": "Prioritize drought-tolerant crops, protect stored water and livestock feed, and contact local agricultural extension services."
        }
        st.subheader("🧑‍🌾 Agricultural Action Recommendations")
        st.info(advice.get(predicted_label, "Consult local agricultural extension experts for location-specific advice."))

        zone = str(input_values.get("Agro_Ecological_Zone", ""))
        drought_crops = {
            "Bereha": ["Pearl millet", "Sorghum", "Cowpea"],
            "Kolla": ["Sorghum", "Pearl millet", "Cowpea", "Sesame"],
            "Woina Dega": ["Teff", "Chickpea", "Lentil"],
            "Dega": ["Barley", "Field pea", "Lentil"]
        }
        normal_crops = {
            "Bereha": ["Sorghum", "Pearl millet", "Sesame"],
            "Kolla": ["Sorghum", "Maize", "Haricot bean"],
            "Woina Dega": ["Teff", "Wheat", "Chickpea"],
            "Dega": ["Barley", "Wheat", "Faba bean"]
        }
        st.subheader("🌱 Crop Suggestions")
        if predicted_label == "No Drought":
            crops = normal_crops.get(zone, ["Sorghum", "Teff", "Barley"])
        else:
            crops = drought_crops.get(zone, ["Sorghum", "Pearl millet", "Cowpea"])
        st.write(" • ".join(crops))
        st.caption("Crop suggestions are general guidance. Confirm suitability with local agronomists and current extension recommendations.")

        result = sample.copy()
        result["Predicted_Drought_Risk"] = predicted_label
        result["Prediction_Probability"] = float(probabilities.max())
        result["Recommended_Crops"] = ", ".join(crops)
        result["Recommended_Actions"] = advice.get(predicted_label, "")
        st.download_button("⬇️ Download Prediction (CSV)",
                           data=result.to_csv(index=False).encode("utf-8-sig"),
                           file_name="drought_prediction_result.csv",
                           mime="text/csv")
    except Exception as exc:
        st.error(f"Prediction failed: {exc}")
        st.warning("Check that this model was trained with the same feature columns and preprocessing pipeline used by this app.")

with st.expander("ℹ️ About this project"):
    st.write(
        "This research dashboard uses the trained machine-learning pipeline supplied with the project. "
        "Predictions depend on the quality, coverage and representativeness of the training data. "
        "Validate outputs with local agricultural experts before making farm-management decisions."
    )
