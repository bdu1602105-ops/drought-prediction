# Import Important Libraries
import os                      # create folders and read environment settings
import shutil                  # copy the trained model beside the Streamlit app
import warnings                # hide harmless warning messages
import numpy as np             # numerical operations
import pandas as pd            # tables (DataFrames) and Excel reading

warnings.filterwarnings("ignore")

# %% 2. Define Project Settings and Variables
# Purpose: keep every setting in one place so it is easy to change later.
BASE_DIR     = os.path.dirname(os.path.abspath(__file__))
DATA_PATH    = os.path.join(BASE_DIR, "Ethiopia_Drought_Risk_Dataset_with_Recommendations.xlsx")  # input file
SHEET_NAME   = "Enhanced_Dataset"      # sheet that holds the data
OUTPUT_DIR   = os.path.join(BASE_DIR, "drought_outputs")       # folder for graphs, model and results
TARGET_COL   = "Drought_Risk_Category" # what we want to predict
RANDOM_STATE = 42                      # makes results repeatable
TEST_SIZE    = 0.20                    # 20% of the data is kept for testing
CV_FOLDS     = 5                       # cross-validation folds used for tuning
# Columns that were created FROM the drought category. If they were used as
# inputs the model would be "cheating" (data leakage), so they are excluded.
LEAKY_COLS = ["Recommended_Crops", "Recommended_Actions"]
#The category is defined from SPI (SPI_3 < -1.0 = Moderate, < -1.5 = Severe).
# Keeping SPI gives ~99% accuracy but partly "answers with the definition".
# Set DROP_DEFINING=1 (or change this to True) to test without those columns.
DROP_TARGET_DEFINING_FEATURES = os.environ.get("DROP_DEFINING", "1") == "1"
TARGET_DEFINING_COLS = ["SPI_3_Month", "SPI_6_Month", "Rainfall_Anomaly_pct"]

os.makedirs(OUTPUT_DIR, exist_ok=True)

# %% 3. Load the Dataset
# Purpose: read the Excel file into a DataFrame and look at the first rows.
try:
    df = pd.read_excel(DATA_PATH, sheet_name=SHEET_NAME)
except FileNotFoundError:
    # Fallback in case the local file name does not match the settings path
    df = pd.read_excel(os.path.join(BASE_DIR, "Ethiopia_Drought_Risk_Dataset.xlsx"))
print("Shape:", df.shape)
print(df.head(3).T)

# %% 4. Check and Clean the Dataset
# Purpose: find missing values and duplicates, and tidy the text columns.
print("\nMissing values:", int(df.isna().sum().sum()))
print("Duplicate rows:", int(df.duplicated().sum()))
df = df.drop_duplicates().reset_index(drop=True)
for c in df.select_dtypes(include="object").columns:
    df[c] = df[c].astype(str).str.strip()          # remove extra spaces
print("Shape after cleaning:", df.shape)

# %% 5. Create the Drought Risk Target
# Purpose: make sure the target exists, then turn its text labels into numbers.
from sklearn.preprocessing import LabelEncoder      # text label -> number

# The dataset already has the target. If it were missing, build it from SPI_3_Month.
if TARGET_COL not in df.columns:
    df[TARGET_COL] = pd.cut(df["SPI_3_Month"], bins=[-np.inf, -1.5, -1.0, np.inf],
                            labels=["Severe Drought", "Moderate Drought", "No Drought"]).astype(str)

label_encoder = LabelEncoder()
y_all = pd.Series(label_encoder.fit_transform(df[TARGET_COL]), name="target")
CLASS_NAMES = list(label_encoder.classes_)
print("\nClasses:", dict(zip(CLASS_NAMES, range(len(CLASS_NAMES)))))
print(df[TARGET_COL].value_counts())               # shows the class imbalance

# %% 6. Select Input Features (X) and Target (y)
# Purpose: choose the columns the model may learn from (X) and what it predicts (y).
drop_cols = [TARGET_COL] + [c for c in LEAKY_COLS if c in df.columns]
if DROP_TARGET_DEFINING_FEATURES:
    drop_cols += [c for c in TARGET_DEFINING_COLS if c in df.columns]
drop_cols += [c for c in df.columns if "date" in c.lower()]   # e.g. Observation_Date

X = df.drop(columns=drop_cols)
y = y_all
num_cols = X.select_dtypes(include="number").columns.tolist()     # numeric features
cat_cols = X.select_dtypes(exclude="number").columns.tolist()     # text features
print("\nNumeric features:", num_cols)
print("Categorical features:", cat_cols)

# %% 7. Preprocess Numerical and Categorical Data
# Purpose: numbers -> fill gaps + scale; text -> fill gaps + one-hot encode.
from sklearn.impute import SimpleImputer             # fills missing values
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer        # applies different steps per column type
from sklearn.pipeline import Pipeline                # chains steps together

preprocessor = ColumnTransformer([
    ("num", Pipeline([("imp", SimpleImputer(strategy="median")),
                      ("sc", StandardScaler())]), num_cols),
    ("cat", Pipeline([("imp", SimpleImputer(strategy="most_frequent")),
                      ("oh", OneHotEncoder(handle_unknown="ignore"))]), cat_cols),
])

# %% 8. Split the Dataset into Training and Testing
# Purpose: keep unseen data for a fair final test.
# stratify=y keeps the same class percentages in both parts (fixes imbalance in the split).
from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=TEST_SIZE, stratify=y, random_state=RANDOM_STATE)
print("\nTrain:", X_train.shape, " Test:", X_test.shape)
print("Train class share:", y_train.value_counts(normalize=True).round(3).to_dict())
print("Test  class share:", y_test.value_counts(normalize=True).round(3).to_dict())

# %% 9. Define the Decision Tree Model
# Purpose: a simple, easy-to-explain model.
# class_weight="balanced" gives rare drought classes a higher importance.
from sklearn.tree import DecisionTreeClassifier

dt_pipe = Pipeline([("prep", preprocessor),
                    ("model", DecisionTreeClassifier(class_weight="balanced",
                                                     random_state=RANDOM_STATE))])
dt_grid = {"model__max_depth": [3, 5, 8, 12, None],       # settings to try
           "model__min_samples_leaf": [1, 3, 5, 10]}

# %% 10. Define the Random Forest Model
# Purpose: many trees voting together; usually more stable than one tree.
from sklearn.ensemble import RandomForestClassifier

rf_pipe = Pipeline([("prep", preprocessor),
                    ("model", RandomForestClassifier(class_weight="balanced_subsample",
                                                     random_state=RANDOM_STATE, n_jobs=-1))])
rf_grid = {"model__n_estimators": [200, 400],
           "model__max_depth": [None, 10, 20],
           "model__min_samples_leaf": [1, 2, 4]}

# %% 11. Define the XGBoost Model
# Purpose: gradient boosting, often the strongest model on tables of data.
# XGBoost has no class_weight option, so balanced sample weights are given when training (section 12).
from xgboost import XGBClassifier

xgb_pipe = Pipeline([("prep", preprocessor),
                     ("model", XGBClassifier(objective="multi:softprob", eval_metric="mlogloss",
                                             random_state=RANDOM_STATE, n_jobs=-1))])
xgb_grid = {"model__n_estimators": [200, 400],
            "model__max_depth": [3, 5, 7],
            "model__learning_rate": [0.05, 0.1]}

# %% 12. Train and Tune the Models
# Purpose: try every setting with stratified 5-fold cross-validation and keep the best.
# Scoring uses macro F1, which treats all three classes equally (accuracy would favour "No Drought").
from sklearn.model_selection import StratifiedKFold, GridSearchCV
from sklearn.utils.class_weight import compute_sample_weight

cv = StratifiedKFold(n_splits=CV_FOLDS, shuffle=True, random_state=RANDOM_STATE)
sw_train = compute_sample_weight("balanced", y_train)    # weights for XGBoost
searches = {}
for name, pipe, grid in [("Decision Tree", dt_pipe, dt_grid),
                         ("Random Forest", rf_pipe, rf_grid),
                         ("XGBoost", xgb_pipe, xgb_grid)]:
    print(f"\nTuning {name} ...")
    gs = GridSearchCV(pipe, grid, cv=cv, scoring="f1_macro", n_jobs=-1)
    if name == "XGBoost":
        gs.fit(X_train, y_train, model__sample_weight=sw_train)
    else:
        gs.fit(X_train, y_train)
    searches[name] = gs
    print("  best params :", gs.best_params_)
    print("  CV macro F1 :", round(gs.best_score_, 4))

# %% 13. Evaluate Model Performance
# Purpose: test each tuned model on the data it has never seen.
from sklearn.metrics import (accuracy_score, f1_score, precision_score, recall_score,
                             classification_report, confusion_matrix)

results, preds = [], {}
for name, gs in searches.items():
    p = gs.best_estimator_.predict(X_test)
    preds[name] = p
    results.append({
        "Model": name,
        "CV Macro F1": gs.best_score_,
        "Test Accuracy": accuracy_score(y_test, p),
        "Test Macro F1": f1_score(y_test, p, average="macro"),
        "Test Macro Precision": precision_score(y_test, p, average="macro"),
        "Test Macro Recall": recall_score(y_test, p, average="macro"),
        # Severe recall = how many real severe droughts were caught (the most important safety measure)
        "Severe Recall": recall_score(y_test, p, labels=[CLASS_NAMES.index("Severe Drought")],
                                      average=None)[0],
    })
    print(f"\n===== {name} =====")
    print(classification_report(y_test, p, target_names=CLASS_NAMES, digits=4))
    print("Confusion matrix:\n", confusion_matrix(y_test, p))

# %% 14. Compare the Three Models
# Purpose: put all results in one table and choose the best model.
# The choice uses the cross-validation score, not the test set, so the test stays fair.
comparison = pd.DataFrame(results).set_index("Model").round(4)
print("\n", comparison)
best_name = comparison["CV Macro F1"].idxmax()
best_model = searches[best_name].best_estimator_
print("\nBest model:", best_name)

# %% 15. Calculate Feature Importance
# Purpose: see which inputs the best model relies on most.
feat_names = best_model.named_steps["prep"].get_feature_names_out()
raw_imp = best_model.named_steps["model"].feature_importances_
importance = (pd.Series(raw_imp, index=feat_names)
              .rename(lambda s: s.replace("num__", "").replace("cat__", ""))
              .sort_values(ascending=False))
print("\nTop 10 features:\n", importance.head(10).round(4))

# %% 16. Create Drought Risk Predictions
# Purpose: predict the drought category (and the model's confidence) for every row.
full_pred = best_model.predict(X)
full_proba = best_model.predict_proba(X)
out = df.copy()
out["Predicted_Drought_Risk"] = label_encoder.inverse_transform(full_pred)
out["Prediction_Confidence"] = full_proba.max(axis=1).round(3)

def predict_new(sample: dict) -> dict:
    """Predict drought risk for ONE new location.
    sample = dictionary containing every column that is in X."""
    row = pd.DataFrame([sample])[X.columns]
    k = best_model.predict(row)[0]
    return {"category": label_encoder.inverse_transform([k])[0],
            "confidence": float(best_model.predict_proba(row).max())}

# %% 17. Generate Agricultural Recommendations
# Purpose: turn each predicted category into simple advice and suggested crops.
ADVICE = {
 "No Drought": "Conditions are good. Plant on time and look after your crops as usual. Keep checking the rain and soil moisture, and save some water in case dry days come.",
 "Moderate Drought": "Some drought is coming. Plant crops that need less water and ripen early. Cover the soil with straw or mulch to keep it moist. Save rain water and use it carefully. Check your fields every week.",
 "Severe Drought": "Serious drought. Plant only crops that survive dry weather and avoid crops that need a lot of water. Store water and animal feed now. Move animals early before they get weak. Ask your local agriculture office for seed, food or livestock support.",
}
CROPS = {   # (normal crops, drought-tolerant crops) for each agro-ecological zone
 "Bereha": (["Sorghum", "Pearl millet", "Cowpea", "Sesame"], ["Pearl millet", "Sorghum", "Cowpea", "Mung bean"]),
 "Kolla": (["Sorghum", "Maize", "Haricot bean", "Sesame", "Groundnut"], ["Sorghum", "Pearl millet", "Mung bean", "Cowpea", "Sesame"]),
 "Woina Dega": (["Teff", "Maize", "Wheat", "Chickpea", "Faba bean"], ["Teff", "Chickpea", "Sorghum", "Lentil", "Field pea"]),
 "Dega": (["Barley", "Wheat", "Faba bean", "Field pea", "Potato"], ["Barley", "Field pea", "Lentil", "Faba bean", "Linseed"]),
}
LEGUMES = {"Faba bean", "Field pea", "Chickpea", "Lentil", "Haricot bean", "Cowpea", "Mung bean", "Groundnut"}

def recommend_crops(row, category):
    """Pick up to 3 crops from the zone, soil, water situation and previous crop."""
    stressed = category != "No Drought" or row["Water_Availability_Index"] < 40 \
               or row["Soil_Moisture_pct"] < 20
    lst = list(CROPS[row["Agro_Ecological_Zone"]][1 if stressed else 0])
    if row["Soil_Type"] == "Leptosols":                       # shallow soil
        lst = [c for c in lst if c not in ("Potato", "Maize", "Faba bean")] or lst
    if row["Soil_Type"] == "Vertisols" and row["Rainfall_mm"] > 900:   # waterlogging risk
        lst = [c for c in lst if c not in ("Haricot bean", "Potato")] or lst
    prev = str(row["Previous_Crop"]).lower()
    lst = [c for c in lst if c.lower() != prev] or lst        # do not repeat the previous crop
    if prev in ("wheat", "barley", "teff", "maize"):
        lst.sort(key=lambda c: 0 if c in LEGUMES else 1)       # cereal -> legume next
    elif prev in ("pulses", "fallow"):
        lst.sort(key=lambda c: 1 if c in LEGUMES else 0)       # legume/fallow -> cereal next
    return ", ".join(lst[:3])

out["Recommended_Crops_Predicted"] = [recommend_crops(r, c) for (_, r), c in
                                      zip(out.iterrows(), out["Predicted_Drought_Risk"])]
out["Recommended_Actions_Predicted"] = out["Predicted_Drought_Risk"].map(ADVICE)

